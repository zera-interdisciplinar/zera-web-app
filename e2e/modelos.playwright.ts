import { AxeBuilder } from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'
import { base, fazerLogin, preparar } from './api-controlada'
import { controlarInventario } from './inventario-controlado'

async function abrir(page: Page, destino: 'Modelos' | 'Configurações' = 'Modelos') {
  await preparar(page, 'MANAGER', 0, base, false)
  const inventory = await controlarInventario(page)
  await fazerLogin(page)
  await page.getByRole('navigation', { name: 'Seções do sistema' }).getByRole('link', { name: destino }).click()
  await expect(page.getByRole('heading', { name: destino, exact: true, level: 1 })).toBeVisible()
  return inventory
}

const dialog = (page: Page) => page.getByRole('dialog')
const rowOf = (page: Page, name: string) => page.getByRole('row').filter({ hasText: name })
const aba = (page: Page, name: string) => page.getByRole('tab', { name })

test('abas Modelos e Categorias com estados ARIA e teclado', async ({ page }) => {
  await abrir(page)
  await expect(aba(page, 'Modelos')).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('table', { name: 'Todos os modelos' })).toBeVisible()
  await aba(page, 'Modelos').press('ArrowRight')
  await expect(aba(page, 'Categorias')).toHaveAttribute('aria-selected', 'true')
  await expect(aba(page, 'Categorias')).toBeFocused()
  await expect(page).toHaveURL(/tab=categorias/)
  await expect(page.getByRole('table', { name: 'Todas as categorias' })).toBeVisible()
  await page.reload()
  await expect(aba(page, 'Categorias')).toHaveAttribute('aria-selected', 'true')
})

test('T-17: lista modelos com aprovação só de leitura e filtro no servidor', async ({ page }) => {
  const inventory = await abrir(page)
  const table = page.getByRole('table', { name: 'Todos os modelos' })
  await expect(table.getByRole('columnheader')).toHaveText(['Modelo', 'Fabricante', 'Categoria', 'Materiais', 'Vida útil', 'Garantia', 'Peso', 'Aprovação', 'Ação'])
  await expect(rowOf(page, 'ThinkPad T14')).toContainText('Aprovado')
  await expect(rowOf(page, 'Modelo sem itens')).toContainText('Pendente')
  // Nobody can approve or reject a model from here: the API has no endpoint for it.
  await expect(page.getByRole('button', { name: /Aprovar|Reprovar/ })).toHaveCount(0)
  await page.getByLabel('Aprovação').selectOption('PENDING')
  await expect(page.getByRole('row')).toHaveCount(2)
  await expect(page).toHaveURL(/approval=PENDING/)
  expect(inventory.lists.at(-1)?.get('approvalStatus')).toBe('PENDING')
})

test('T-17: criar modelo valida no navegador e envia o corpo do contrato', async ({ page }) => {
  const inventory = await abrir(page)
  await page.getByRole('button', { name: 'Novo modelo' }).click()
  const form = dialog(page)
  await form.getByRole('button', { name: 'Cadastrar modelo' }).click()
  for (const message of ['Informe o nome.', 'Informe o fabricante.', 'Selecione a categoria.', 'Selecione ao menos um material.']) await expect(form.getByText(message)).toBeVisible()
  expect(inventory.writes).toEqual([])
  await form.getByLabel('Nome do modelo').fill('Galaxy Tab')
  await form.getByLabel('Fabricante').fill('Samsung')
  await form.getByLabel(/^Categoria/).selectOption('cat-eletronicos')
  await form.getByLabel('Plástico').check()
  await form.getByLabel('Garantia (meses)').fill('0')
  await form.getByRole('button', { name: 'Cadastrar modelo' }).click()
  await expect(form.getByText('Informe um número inteiro de meses maior que zero.')).toBeVisible()
  await form.getByLabel('Garantia (meses)').fill('24')
  await form.getByRole('button', { name: 'Cadastrar modelo' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Modelo cadastrado.' })).toBeVisible()
  expect(inventory.writes).toEqual([{ method: 'POST', path: '/api/v1/models', body: { name: 'Galaxy Tab', manufacturer: 'Samsung', categoryId: 'cat-eletronicos', materials: ['PLASTIC'], warrantyMonths: 24 } }])
  await expect(rowOf(page, 'Galaxy Tab')).toBeVisible()
})

test('T-17: editar salva cada campo no seu PATCH, só os que mudaram', async ({ page }) => {
  const inventory = await abrir(page)
  await page.getByRole('button', { name: 'Editar Modelo sem itens' }).click()
  const form = dialog(page)
  await expect(form.getByText('não pode ser alterada')).toBeVisible()
  await form.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(dialog(page)).toBeHidden()
  expect(inventory.writes).toEqual([])

  await page.getByRole('button', { name: 'Editar Modelo sem itens' }).click()
  await form.getByLabel('Nome do modelo').fill('Modelo renomeado')
  await form.getByLabel('Garantia (meses)').fill('36')
  await form.getByLabel('Vidro').check()
  await form.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Modelo atualizado.' })).toBeVisible()
  expect(inventory.writes.map((write) => `${write.method} ${write.path.replace('/api/v1/models/model-3', '')}`)).toEqual(['PATCH /name', 'PATCH /warranty-months', 'PATCH /materials'])
  expect(inventory.writes.map((write) => write.body)).toEqual([{ name: 'Modelo renomeado' }, { warrantyMonths: 36 }, { materials: ['METAL', 'GLASS'] }])
  await expect(rowOf(page, 'Modelo renomeado')).toBeVisible()
})

