test('T-16: categoria exige nome e descrição, renomeia, edita a descrição e só exclui se não estiver em uso', async ({ page }) => {
  const inventory = await abrir(page)
  await aba(page, 'Categorias').click()
  await page.getByRole('button', { name: 'Nova categoria' }).click()
  await dialog(page).getByRole('button', { name: 'Criar categoria' }).click()
  await expect(dialog(page).getByText('Informe o nome.')).toBeVisible()
  await expect(dialog(page).getByText('Informe a descrição.')).toBeVisible()
  expect(inventory.writes).toEqual([])
  await dialog(page).getByLabel('Nome').fill('Cabos')
  await dialog(page).getByLabel('Descrição').fill('Cabos e fontes')
  await dialog(page).getByRole('button', { name: 'Criar categoria' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Categoria criada.' })).toBeVisible()
  expect(inventory.writes[0]).toMatchObject({ method: 'POST', path: '/api/v1/categories', body: { name: 'Cabos', description: 'Cabos e fontes' } })

  await page.getByRole('button', { name: 'Editar categoria Cabos' }).click()
  await dialog(page).getByLabel('Nome').fill('Cabos e fontes')
  await dialog(page).getByLabel('Descrição').fill('Tudo de energia')
  await dialog(page).getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(rowOf(page, 'Cabos e fontes')).toBeVisible()
  expect(inventory.writes.slice(1).map((write) => `${write.method} ${write.path.split('/').slice(-1)[0]}`)).toEqual(['PATCH name', 'PATCH description'])

  await page.getByRole('button', { name: 'Excluir categoria Eletrônicos' }).click()
  await dialog(page).getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(dialog(page).getByRole('alert')).toContainText('Categoria em uso por modelos')
  await dialog(page).getByRole('button', { name: 'Cancelar' }).click()
  await page.getByRole('button', { name: 'Excluir categoria Sem uso' }).click()
  await dialog(page).getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Categoria excluída.' })).toBeVisible()
  await expect(rowOf(page, 'Sem uso')).toHaveCount(0)
})

test('T-18: configurações mostra "Não configurada", valida e salva a capacidade com PUT', async ({ page }) => {
  const inventory = await abrir(page, 'Configurações')
  await expect(page.getByText('Não configurada')).toBeVisible()
  await expect(page.getByText(/ocupação do estoque e a regra de alerta/)).toBeVisible()
  const field = page.getByLabel('Capacidade (itens)')
  await page.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByText('Informe a capacidade do estoque.')).toBeVisible()
  await field.fill('-1')
  await page.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByText('A capacidade não pode ser negativa.')).toBeVisible()
  expect(inventory.writes).toEqual([])
  await field.fill('0')
  await page.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Capacidade do estoque salva.' })).toBeVisible()
  expect(inventory.writes).toEqual([{ method: 'PUT', path: '/api/v1/unit-settings', body: { stockCapacity: 0 } }])
  // Zero is a configured value, different from "not configured".
  await expect(page.getByText('Não configurada')).toHaveCount(0)
  await expect(page.getByText(/Última alteração em .* por Pessoa local/)).toBeVisible()
  await field.fill('250')
  await page.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByText('250', { exact: true })).toBeVisible()
  expect(inventory.writes.at(-1)?.body).toEqual({ stockCapacity: 250 })
})

test('T-24: modelos, categorias, configurações e os diálogos não têm violações graves (axe)', async ({ page }) => {
  await abrir(page)
  const serious = async () => (await new AxeBuilder({ page }).analyze()).violations.filter((item) => item.impact === 'critical' || item.impact === 'serious').map((item) => `${item.id}: ${item.nodes.map((node) => node.target.join(' ')).join(' | ')}`)
  expect(await serious()).toEqual([])
  await page.getByRole('button', { name: 'Novo modelo' }).click()
  await dialog(page).getByRole('button', { name: 'Cadastrar modelo' }).click()
  await expect(dialog(page).getByText('Informe o nome.')).toBeVisible()
  expect(await serious()).toEqual([])
  await page.keyboard.press('Escape')
  await aba(page, 'Categorias').click()
  expect(await serious()).toEqual([])
  await page.getByRole('link', { name: 'Configurações' }).click()
  await expect(page.getByText('Capacidade do estoque').first()).toBeVisible()
  expect(await serious()).toEqual([])
})
